/**
 * Bundles the extension into one JavaScript file, `dist/index.js`. Pi transpiles TypeScript on every
 * start and `/reload`; one bundled file loads in milliseconds instead of over a second.
 * `--check` builds in memory and fails when `dist/index.js` is not what the sources produce.
 */
import { readFileSync } from 'node:fs';
import { build } from 'esbuild';

const OUT = 'dist/index.js';
const checking = process.argv.includes('--check');

const result = await build({
  entryPoints: ['src/index.ts'],
  outfile: OUT,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  // Pi supplies these to every extension; they are never bundled.
  external: ['@earendil-works/*', 'typebox'],
  legalComments: 'none',
  banner: { js: '// Footer Dock. Generated by `npm run build` from src/; do not edit.' },
  logLevel: 'warning',
  write: !checking,
});

if (checking) {
  const built = result.outputFiles?.[0]?.text;
  const current = readFileSync(OUT, 'utf8');
  if (built !== current) {
    process.stderr.write(`${OUT} is out of date: run "npm run build" and commit it.\n`);
    process.exit(1);
  }
  process.stdout.write(`${OUT} is up to date\n`);
}
